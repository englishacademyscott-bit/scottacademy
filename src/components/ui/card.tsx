import * as React from "react";
import { cn } from "@/lib/utils";

export const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { variant?: "default" | "glass" | "outline" }
>(({ className, variant = "default", ...props }, ref) => {
  const variants = {
    default: "bg-surface border-subtle shadow-soft",
    glass:
      "bg-surface/70 backdrop-blur-xl border-white/10 dark:border-white/10 shadow-lifted",
    outline: "bg-transparent border-default",
  };
  return (
    <div
      ref={ref}
      className={cn(
        "rounded-xl border transition-all duration-300",
        variants[variant],
        className,
      )}
      {...props}
    />
  );
});
Card.displayName = "Card";

